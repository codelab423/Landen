  // All climate series of a country: [{ nl, en, T, P }], the main city first.
  function series(code) {
    var d = DATA[code];
    if (!d) return [];
    var out = [{ nl: city(code, 'nl'), en: city(code, 'en'), T: d[1], P: d[2] }];
    (REGIONS[code] || []).forEach(function (r) {
      out.push({ nl: r[0], en: r[1], T: r[2], P: r[3] });
    });
    return out;
  }

  // Accepts a country code (main city) or one entry from series().
  function toSeries(key) {
    if (key && key.T) return key;
    var d = DATA[key];
    return d ? { T: d[1], P: d[2] } : null;
  }

  // How pleasant is a month for a holiday? 0 = perfect, lower = worse.
  // Comfortable: a monthly mean of 18-27 °C (days are warmer than the mean) and little rain;
  // cold, heat and lots of rain all cost points.
  function monthScore(t, p) {
    var temp = t < 18 ? 18 - t : t > 27 ? (t - 27) * 1.5 : 0;
    var rain = p > 60 ? (p - 60) / 25 : 0;
    return -(temp + rain);
  }

  // Best months: everything within 1.5 points of the best month.
  // (bestRanges keeps at most the two best periods, so the label stays short.)
  function bestRanges(code) {
    var b = bestMonths(code);
    if (!b) return [];
    return monthRanges(b.months)
      .map(function (r) {
        var sum = 0;
        for (var m = r[0]; ; m = (m + 1) % 12) {
          sum += b.scores[m] - Math.min.apply(null, b.scores) + 1;
          if (m === r[1]) break;
        }
        return { range: r, weight: sum };
      })
      .sort(function (a, b2) {
        return b2.weight - a.weight;
      })
      .slice(0, 2)
      .map(function (x) {
        return x.range;
      })
      .sort(function (a, b2) {
        return a[0] - b2[0];
      });
  }

  function bestMonths(code) {
    var d = toSeries(code);
    if (!d) return null;
    var scores = d.T.map(function (t, i) {
      return monthScore(t, d.P[i]);
    });
    var top = Math.max.apply(null, scores);
    var best = [];
    scores.forEach(function (s, i) {
      if (s >= top - 1.5) best.push(i);
    });
    return { months: best, top: scores.indexOf(top), scores: scores };
  }

  // Group month numbers (0-11) into ranges, also across New Year: [10,11,0,1] -> [[10,1]].
  function monthRanges(months) {
    if (!months.length) return [];
    if (months.length === 12) return [[0, 11]];
    var set = {};
    months.forEach(function (m) {
      set[m] = 1;
    });
    var start = 0;
    while (set[start] && set[(start + 11) % 12]) start = (start + 1) % 12; // start just after a gap
    var ranges = [];
    var cur = null;
    for (var k = 0; k < 12; k++) {
      var m = (start + k) % 12;
      if (set[m]) {
        if (cur) cur[1] = m;
        else cur = [m, m];
      } else if (cur) {
        ranges.push(cur);
        cur = null;
      }
    }
    if (cur) ranges.push(cur);
    return ranges;
  }

